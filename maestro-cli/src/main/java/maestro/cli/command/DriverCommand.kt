package maestro.cli.command

import maestro.cli.driver.DriverBuilder
import maestro.cli.driver.IOSSimulatorDriver
import maestro.cli.driver.RealIOSDeviceDriver
import maestro.cli.util.PrintUtils
import picocli.CommandLine
import java.util.concurrent.Callable

@CommandLine.Command(
    name = "driver-setup",
    description = [
        "Build the TapCue iOS driver from source: for real iOS devices (--apple-team-id) or for the iOS Simulator (--simulator)"
    ],
    hidden = true
)
class DriverCommand : Callable<Int> {

    @CommandLine.Option(
        names = ["--apple-team-id"],
        description = ["The Team ID is a unique 10-character string generated by Apple that is assigned to your team's Apple account."],
        hidden = true
    )
    private var appleTeamId: String? = null

    @CommandLine.Option(
        names = ["--destination"],
        description = ["Destination device to build the driver for. Defaults to generic/platform=iphoneos if not specified."],
        hidden = true
    )
    private var destination: String? = null

    @CommandLine.Option(
        names = ["--simulator"],
        description = ["Build (or rebuild) the iOS Simulator driver now instead of on first use. Requires Xcode."],
        hidden = true
    )
    private var simulator: Boolean = false

    override fun call(): Int {
        if (simulator) {
            val products = IOSSimulatorDriver().buildProducts(force = true)
            PrintUtils.message("iOS Simulator driver built: $products")
            return 0
        }

        val teamId = requireNotNull(appleTeamId) { "Apple account team ID must be specified." }
        val destination = destination ?: "generic/platform=iphoneos"

        val driverBuilder = DriverBuilder()

        RealIOSDeviceDriver(
            teamId = teamId,
            destination = destination,
            driverBuilder = driverBuilder,
        ).validateAndUpdateDriver(force = true)

        return 0
    }
}